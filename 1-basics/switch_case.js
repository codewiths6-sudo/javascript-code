const day = "Sunday";

switch (day) {
  case "Saturday":
    console.log("It's the start of the weekend!");
    break;
  case "Sunday":
    console.log("Time to review code and practice!");
    break;
  case "Friday":
    console.log("It's Friday, weekend is here!");
    break;
  default:
    console.log("It's a regular coding day.");
}